const LanguageContext = createContext<LanguageContextType | undefined>(undefined);

const VALID_LANGS: Language[] = ['ug', 'en', 'ar', 'tr', 'uz', 'ru'];

export function LanguageProvider({ children }: { children: React.ReactNode }) {
  const [lang, setLangState] = useState<Language>('ug');

  useEffect(() => {
    try {
      const savedLang = localStorage.getItem('autocash_lang') as Language;
      if (savedLang && VALID_LANGS.includes(savedLang)) {
        setLangState(savedLang);
        applyLanguageToDocument(savedLang);
      } else {
        applyLanguageToDocument('ug');
      }
    } catch {
      applyLanguageToDocument('ug');
    }
  }, []);

  const applyLanguageToDocument = (l: Language) => {
    if (typeof document !== 'undefined') {
      const isRightToLeft = l === 'ug' || l === 'ar';
      const dir = isRightToLeft ? 'rtl' : 'ltr';
      document.documentElement.lang = l;
      document.documentElement.dir = dir;

      VALID_LANGS.forEach((item) => {
        if (item === l) {
          document.body.classList.add(`lang-${item}`);
        } else {
          document.body.classList.remove(`lang-${item}`);
        }
      });
    }
  };

  const setLang = (newLang: Language) => {
    if (!VALID_LANGS.includes(newLang)) return;
    setLangState(newLang);
    try {
      localStorage.setItem('autocash_lang', newLang);
    } catch (e) {
      console.error(e);
    }
    applyLanguageToDocument(newLang);
  };

  const t = (key: string): string => {
    return TRANSLATIONS[lang]?.[key] || TRANSLATIONS.ug[key] || key;
  };

  const getCategoryName = (id: string, defaultName: string): string => {
    if (lang === 'ug') {
      return defaultName && defaultName.trim() ? defaultName.trim() : CATEGORY_NAMES[id]?.ug || id;
    }
    return CATEGORY_NAMES[id]?.[lang] || defaultName || id;
  };

  const getCategoryCount = (id: string, defaultCount: string): string => {
    return CATEGORY_COUNTS[id]?.[lang] || defaultCount;
  };

  const translatePackageTitle = (title: string): string => {
    return smartTranslateTitle(title, lang);
  };

  const translateBadge = (badge?: string): string | undefined => {
    if (!badge) return undefined;
    if (lang === 'ug') return badge;
    if (badge === 'ئەڭ قىزىق' || badge === 'HOT') {
      if (lang === 'ar') return 'الأكثر طلباً';
      if (lang === 'tr') return 'POPÜLER';
      if (lang === 'uz') return 'ENG MASHHUR';
      if (lang === 'ru') return 'ТОП';
      return 'HOT';
    }
    if (badge === 'يېڭى' || badge === 'NEW') {
      if (lang === 'ar') return 'جديد';
      if (lang === 'tr') return 'YENİ';
      if (lang === 'uz') return 'YANGI';
      if (lang === 'ru') return 'НОВИНКА';
      return 'NEW';
    }
    if (badge === 'مەخسۇس' || badge === 'SPECIAL') {
      if (lang === 'ar') return 'مميز';
      if (lang === 'tr') return 'ÖZEL';
      if (lang === 'uz') return 'MAXSUS';
      if (lang === 'ru') return 'АКЦИЯ';
      return 'SPECIAL';
    }
    return badge;
  };

  const translateInputLabel = (label?: string): string | undefined => {
    if (!label) return undefined;
    return smartTranslateFieldLabel(label, lang);
  };

  const translateInputPlaceholder = (placeholder?: string): string | undefined => {
    if (!placeholder) return undefined;
    if (lang === 'ug') return placeholder;

    const lower = placeholder.toLowerCase();
    if (lower.includes('ئويۇندىكى كىملىك') || lower.includes('player id') || lower.includes('معرف')) {
      if (lang === 'ar') return 'أدخل معرف اللاعب ID الخاص بك في اللعبة';
      if (lang === 'tr') return 'Oyundaki Oyuncu ID numaranızı girin';
      if (lang === 'uz') return 'O‘yindagi Player ID raqamingizni kiriting';
      if (lang === 'ru') return 'Введите ваш Player ID в игре';
      return 'Enter your in-game Player ID';
    }

    if (lang === 'ar') return 'أدخل البيانات المطلوبة هنا...';
    if (lang === 'tr') return 'Gerekli bilgileri girin...';
    if (lang === 'uz') return 'Talab qilingan ma’lumotlarni kiriting...';
    if (lang === 'ru') return 'Введите необходимые данные...';
    return 'Enter required details...';
  };

  const dir: 'rtl' | 'ltr' = lang === 'ug' || lang === 'ar' ? 'rtl' : 'ltr';
  const isRTL = dir === 'rtl';

  return (
    <LanguageContext.Provider
      value={{
        lang,
        setLang,
        t,
        dir,
        isRTL,
        getCategoryName,
        getCategoryCount,
        translatePackageTitle,
        translateBadge,
        translateInputLabel,
        translateInputPlaceholder,
      }}
    >
      {children}
    </LanguageContext.Provider>
  );
}

export function useLanguage() {
  const context = useContext(LanguageContext);
  if (!context) {
    throw new Error('useLanguage must be used within a LanguageProvider');
  }
  return context;
}
